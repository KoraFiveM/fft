local function step(pattern,realm,capability,callback)
    FFT.registerStep({pattern=pattern,realm=realm,requires={capability}},callback)
end
step('I am alive','client','player.alive',function(ctx)
    assert(ctx:call('player.alive'),'Player is not alive')
end)
step('I am at the configured soda vending machine','client','fixture.approach',function(ctx)
    ctx:call('fixture.approach')
end)
step('I have enough cash and inventory capacity for {int} {string}','server','purchase.prepare',function(ctx,n,item)
    ctx:call('purchase.prepare',n,item)
end)
step('I select {string} on the machine','client','target.select',function(ctx,label)
    ctx:call('target.select',label)
end)
step('I buy {int} {string} through the inventory UI','client','ui.buy',function(ctx,n,item)
    ctx:call('ui.buy',n,item)
end)
step('my inventory should contain {int} more {string}','server','purchase.assertItem',function(ctx,n,item)
    ctx:call('purchase.assertItem',n,item)
end)
step('my cash should have decreased by {int}','server','purchase.assertCash',function(ctx,n)
    ctx:call('purchase.assertCash',n)
end)

step('I am on foot','client','player.onFoot',function(ctx)
    assert(ctx:call('player.onFoot'),'Player must be on foot')
end)
step('I remember my position','client','player.position',function(ctx)
    ctx.state.position = ctx:call('player.position')
end)
step('I should be within {int} metres of my remembered position','client','player.position',function(ctx,radius)
    assert(radius >= 0,'Radius must be nonnegative')
    local before = assert(ctx.state.position,'Remember a position first')
    local now = ctx:call('player.position')
    local distance = math.sqrt((now.x-before.x)^2+(now.y-before.y)^2+(now.z-before.z)^2)
    assert(distance <= radius,('Player moved %.2f metres (limit %d)'):format(distance,radius))
end)
step('I face heading {int}','client','player.setHeading',function(ctx,n)
    ctx:call('player.setHeading',n)
end)
step('my heading should be {int}','client','player.heading',function(ctx,n)
    ctx:waitUntil(function() return math.abs((ctx:call('player.heading')-n+180)%360-180)<1 end,'Heading differs by more than one degree')
end)
step('I set my armour to {int}','client','player.setArmour',function(ctx,n)
    ctx:call('player.setArmour',n)
end)
step('my armour should be {int}','client','player.armour',function(ctx,n)
    ctx:equal(ctx:call('player.armour'),n,'Player armour')
end)
step('a soda machine should be nearby','client','entity.nearby',function(ctx)
    local p = ctx:call('player.position')
    assert(ctx:call('entity.nearby','prop_vend_soda_01',p,3.0) or
        ctx:call('entity.nearby','prop_vend_soda_02',p,3.0),'No soda machine within three metres')
end)

step('my player model should be valid','client','player.modelValid',function(ctx)
