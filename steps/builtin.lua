end)
step('I set my health to maximum','client','player.setHealth',function(ctx)
    ctx:call('player.setHealth',ctx:call('player.maxHealth'))
end)
step('I lower my health by {int}','client','player.setHealth',function(ctx,amount)
    assert(amount>0 and amount<100,'Health reduction must be 1–99')
    ctx:call('player.setHealth',ctx:call('player.health')-amount)
end)
step('my health should be {int} below maximum','client','player.health',function(ctx,amount)
    ctx:equal(ctx:call('player.health'),ctx:call('player.maxHealth')-amount,'Player health')
end)
