Given('the example player is alive', {realm='client'}, function(ctx)
    assert(not IsEntityDead(PlayerPedId()), 'Player is dead')
end)
Then('the example player has a server ped', {realm='server'}, function(ctx)
    ctx:waitUntil(function()
        local ped = GetPlayerPed(ctx.tester)
        return ped ~= 0 and DoesEntityExist(ped)
    end, 'Tester has no server ped; enable OneSync')
end)
